// Package assetsum fingerprints the inputs of the compiled admin
// stylesheet (internal/web/static/admin.css). The generator
// (internal/web/tools/genadmincss) stamps the fingerprint into the CSS
// header; TestAdminCSSFresh recomputes it and fails when the committed
// CSS was built from different inputs. Keeping both sides on one function
// is what makes the staleness check trustworthy.
package assetsum

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
)

// HeaderPrefix starts the first line of admin.css.
const HeaderPrefix = "/*! sieve admin.css inputs-sha256:"

// Inputs returns the slash-separated paths, relative to the internal/web
// directory, that the Tailwind build reads: the theme source and every
// template it scans for class names.
func Inputs(webFS fs.FS) ([]string, error) {
	tmpl, err := fs.Glob(webFS, "templates/*.html")
	if err != nil {
		return nil, err
	}
	out := append([]string{"styles/theme.css"}, tmpl...)
	sort.Strings(out)
	return out, nil
}

// Sum hashes the build inputs found in webFS (rooted at internal/web).
// Line endings are normalised so a CRLF checkout does not look stale.
func Sum(webFS fs.FS) (string, error) {
	files, err := Inputs(webFS)
	if err != nil {
		return "", err
	}
	h := sha256.New()
	for _, f := range files {
		b, err := fs.ReadFile(webFS, f)
		if err != nil {
			return "", fmt.Errorf("assetsum: %w", err)
		}
		norm := strings.ReplaceAll(string(b), "\r\n", "\n")
		fmt.Fprintf(h, "%s\n%d\n", path.Clean(f), len(norm))
		h.Write([]byte(norm))
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// Header is the first line the generator writes into admin.css.
func Header(sum string) string {
	return HeaderPrefix + sum + " (generated by go generate ./internal/web; do not edit) */\n"
}
